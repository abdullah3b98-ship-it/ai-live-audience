const WebSocket = require('ws');
const B = process.env.BASE || 'http://localhost:3000';
const j = (u, b) => fetch(B + u, { method: b ? 'POST' : 'GET', headers: { 'content-type': 'application/json' }, body: b ? JSON.stringify(b) : undefined }).then((r) => r.json());
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const settings = { total: 14, mode: 'counts', girls: 9, boys: 5, politeness: 'mixed', tease: 60, curse: 50, activity: 80, debate: 60, streamerName: 'أبو سلطان' };
  const prev = await j('/api/audience/preview', settings);
  console.log('preview', prev.length, 'girls', prev.filter((p) => p.gender === 'f').length);
  const { id } = await j('/api/streams/start', { title: 'test', game: 'FIFA', settings, personas: prev });
  const ws = new WebSocket(B.replace('http', 'ws') + '/ws?stream=' + id);
  const out = [];
  ws.on('message', (d) => { const m = JSON.parse(d); if (m.type === 'message') { out.push(m.msg); console.log(`[${m.msg.kind}] ${m.msg.username || ''}${m.msg.replyTo ? ' ↩' + m.msg.replyTo.name : ''}: ${m.msg.text}`); } else if (m.type === 'reaction') console.log('  (reaction)', m.username, m.emoji); else if (m.type === 'highlight') console.log('  HIGHLIGHT', m.label); });
  await new Promise((r) => ws.on('open', r));
  const send = (o) => ws.send(JSON.stringify(o));
  await sleep(8000);
  send({ type: 'chat', text: 'السلام عليكم يا جماعة' }); await sleep(7000);
  send({ type: 'chat', text: 'مره واحد محشش دخل مطعم وطلب نص دجاجة قالوا له ليش قال انا رجيم' }); await sleep(9000);
  send({ type: 'action', action: 'fail' }); await sleep(7000);
  const name = prev[0].username;
  send({ type: 'chat', text: `@${name} وش رأيك؟` }); await sleep(5000);
  send({ type: 'chat', text: 'والله اليوم الوضع دلخ مره' }); await sleep(12000);
  send({ type: 'detect', objects: [{ label: 'remote', score: 0.55, bbox: [0.3, 0.3, 0.2, 0.2] }] }); await sleep(7000);
  send({ type: 'chat', text: 'هذا اسمه يد بلايستيشن 5' }); await sleep(6000);
  send({ type: 'chat', text: 'زقنبي يعني شي مزعج وثقيل' }); await sleep(6000);
  const st = await j(`/api/streams/${id}/state`);
  console.log('viewers', st.viewers);
  await j(`/api/streams/${id}/end`, {});
  console.log('TOTAL persona msgs', out.filter((m) => m.pid).length);
  const texts = out.filter((m) => m.pid).map((m) => m.text); console.log('unique', new Set(texts).size, '/', texts.length);
  process.exit(0);
})();
