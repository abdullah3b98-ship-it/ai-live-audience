function merge(base, extra, subs = null) {
  const out = {};
  const tr = (x) => { if (!subs) return x; let t = x; for (const [a, b] of subs) t = t.replace(a, b); return t; };
  for (const k of Object.keys(base)) out[k] = [...new Set([...(extra[k] || []), ...base[k].map(tr)])];
  return out;
}
